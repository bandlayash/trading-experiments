"""Score all three strategies on identical bars, identical costs, identical conventions.

This is the file that produces `results/benchmark.md`. Everything published in this repo
comes from running it -- no hand-copied numbers.

    python run_benchmark.py                 # print the tables
    python run_benchmark.py --write         # also refresh results/benchmark.md + CSVs
    python run_benchmark.py --signal SPY --trade SPY    # any pair you like
"""

from __future__ import annotations

import argparse
import datetime as dt
import os

import pandas as pd

from common import load_pair, buy_and_hold, perf_stats, split_stats, sub_period_sharpe
from common.engine import COST_PER_SIDE
from strategies import donchian_aroon, ema_rsi_meanrev, seykota, sma_momentum

OOS_START = "2020-01-01"
WARMUP = 252
RESULTS_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "results")

HEADER = (f"{'Strategy':<22}{'Sharpe':>8}{'IS':>7}{'OOS':>7}{'CAGR':>9}"
          f"{'Vol':>8}{'MaxDD':>9}{'Growth':>9}{'Exp':>7}{'Trades/yr':>11}")


def _row(name: str, ret: pd.Series, exposure: float, trades: float | None) -> str:
    s = split_stats(ret, OOS_START)
    a = s["all"]
    trades_str = f"{trades:.1f}" if trades is not None else "-"
    return (f"{name:<22}{a['sharpe']:>8.2f}{s['is']['sharpe']:>7.2f}"
            f"{s['oos']['sharpe']:>7.2f}{a['cagr']*100:>8.1f}%{a['ann_vol']*100:>7.1f}%"
            f"{a['max_dd']*100:>8.1f}%{a['equity_mult']:>8.1f}x{exposure*100:>6.0f}%"
            f"{trades_str:>11}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--signal", default="SMH", help="instrument the trend is read from")
    ap.add_argument("--trade", default="SOXL", help="instrument actually held")
    ap.add_argument("--write", action="store_true", help="refresh results/ artifacts")
    args = ap.parse_args()

    signal, traded = load_pair(args.signal, args.trade)
    results = [mod.run(signal, traded, warmup=WARMUP)
               for mod in (donchian_aroon, sma_momentum, seykota, ema_rsi_meanrev)]
    idx = results[0].daily_ret.index

    benchmarks = [buy_and_hold(traded, idx, f"Buy & hold {args.trade}"),
                  buy_and_hold(signal, idx, f"Buy & hold {args.signal}")]

    lines = []

    def emit(text: str = "") -> None:
        print(text)
        lines.append(text)

    emit("=" * len(HEADER))
    emit(f"Trend-following benchmark  |  signal={args.signal}  traded={args.trade}")
    emit(f"{idx[0].date()} -> {idx[-1].date()}  ({len(idx)} trading days)  "
         f"IS < {OOS_START} <= OOS")
    emit(f"Costs {COST_PER_SIDE*1e4:.0f} bps/side.  Sharpe at 0% risk-free.")
    emit("=" * len(HEADER))
    emit(HEADER)
    for r in sorted(results, key=lambda r: perf_stats(r.daily_ret)["sharpe"], reverse=True):
        emit(_row(r.name, r.daily_ret, r.exposure, r.trades_per_year))
    emit("-" * len(HEADER))
    for b in benchmarks:
        emit(_row(b.name, b.daily_ret, b.exposure, None))
    emit("=" * len(HEADER))

    emit("")
    emit("Four-year sub-period Sharpe (regime consistency):")
    periods = list(sub_period_sharpe(results[0].daily_ret).keys())
    emit(f"{'Strategy':<22}" + "".join(f"{p:>12}" for p in periods))
    for r in results + benchmarks:
        cells = sub_period_sharpe(r.daily_ret)
        emit(f"{r.name:<22}" + "".join(f"{cells[p]:>12.2f}" for p in periods))

    emit("")
    emit("Parameters used:")
    for r in results:
        emit(f"  {r.name:<20} {r.params}")

    if args.write:
        os.makedirs(RESULTS_DIR, exist_ok=True)
        stamp = dt.date.today().isoformat()
        md = os.path.join(RESULTS_DIR, "benchmark.md")
        with open(md, "w", encoding="utf-8") as fh:
            fh.write("# Benchmark results\n\n")
            fh.write(f"Generated by `python run_benchmark.py --write` on **{stamp}**.\n")
            fh.write("Do not edit by hand -- rerun the command.\n\n```\n")
            fh.write("\n".join(lines))
            fh.write("\n```\n")

        curves = pd.DataFrame({r.name: r.equity_curve() for r in results + benchmarks})
        curves.to_csv(os.path.join(RESULTS_DIR, "equity_curves.csv"))
        rows = []
        for r in results + benchmarks:
            s = split_stats(r.daily_ret, OOS_START)
            rows.append({"strategy": r.name, "sharpe": s["all"]["sharpe"],
                         "is_sharpe": s["is"]["sharpe"], "oos_sharpe": s["oos"]["sharpe"],
                         "cagr": s["all"]["cagr"], "ann_vol": s["all"]["ann_vol"],
                         "max_dd": s["all"]["max_dd"],
                         "equity_mult": s["all"]["equity_mult"],
                         "exposure": r.exposure, "trades_per_yr": r.trades_per_year})
        pd.DataFrame(rows).to_csv(os.path.join(RESULTS_DIR, "summary.csv"), index=False)
        print(f"\nWrote {md}, equity_curves.csv, summary.csv")


if __name__ == "__main__":
    main()
